"""Write an MTL companion file from libssynth's color-group OBJ.

The patched ssynthgen emits `g <name>#rrggbb` / `usemtl <name>#rrggbb`
group markers. This module turns those into a proper .mtl that any
OBJ viewer (Blender, MeshLab, Windows 3D Viewer) understands.
"""

from __future__ import annotations

import re
from pathlib import Path

_GROUP_RE = re.compile(r"^g\s+(\S+)")
_HEX_RE = re.compile(r"#([0-9a-fA-F]{6})")


def obj_group_colors(obj_path: str | Path) -> dict[str, str]:
    """Return {material_name: '#rrggbb'} from an OBJ's g/usemtl lines."""
    colors: dict[str, str] = {}
    with Path(obj_path).open("r", encoding="utf-8", errors="replace") as fh:
        for line in fh:
            if line.startswith("g ") or line.startswith("usemtl "):
                name = line.split(None, 1)[1].strip() if " " in line else ""
                m = _HEX_RE.search(name)
                if m:
                    colors[name] = "#" + m.group(1).lower()
    return colors


def write_mtl(obj_path: str | Path, mtl_path: str | Path | None = None) -> str | None:
    """Create a .mtl next to the OBJ from its color groups. Returns the path
    (or None if the OBJ has no color groups). Also injects `mtllib` at the
    top of the OBJ so viewers pick it up.
    """
    src = Path(obj_path)
    colors = obj_group_colors(src)
    if not colors:
        return None

    out = Path(mtl_path) if mtl_path else src.with_suffix(".mtl")
    lines = ["# Generated by structuresynth-mcp"]
    for name, hexcolor in colors.items():
        r = int(hexcolor[1:3], 16) / 255.0
        g = int(hexcolor[3:5], 16) / 255.0
        b = int(hexcolor[5:7], 16) / 255.0
        lines += [
            f"newmtl {name}",
            f"Kd {r:.6f} {g:.6f} {b:.6f}",
            "Ka 0.000000 0.000000 0.000000",
            "Ks 0.100000 0.100000 0.100000",
            "Ns 32.000000",
            "d 1.000000",
            "illum 2",
            "",
        ]
    out.write_text("\n".join(lines), encoding="utf-8")

    # Inject `mtllib <name>.mtl` as the first line if not already present.
    text = src.read_text(encoding="utf-8", errors="replace")
    if not text.startswith("mtllib "):
        src.write_text(f"mtllib {out.name}\n" + text, encoding="utf-8")
    return str(out)
